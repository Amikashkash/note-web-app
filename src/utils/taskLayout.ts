/**
 * הפריסה של שורת משימה ברוחב של טלפון (v1.43.1, v1.44.1): מתי הכפתורים
 * (תאריך, שעה, עדיפות, מחיקה) יורדים לשורה משלהם, כדי שלטקסט יישאר רוחב.
 */

/**
 * מעל האורך הזה הכפתורים של משימה בלי תאריך יורדים לשורה משלהם (v1.43.1).
 * בערך 6-7 מילים: מה שנכנס לשתי שורות ליד הכפתורים ברוחב של טלפון.
 */
export const LONG_TASK_CHARS = 40;

/**
 * האם הכפתורים של המשימה יורדים לשורה משלהם.
 *
 * **משימה עם תאריך - תמיד** (v1.44.1). עם תאריך יש בשורה גם בורר שעה ושני
 * כפתורי X, ולטקסט נשארים כ-90px בטלפון: בבדיקה עם נתונים ריאליסטיים גם
 * "לשלם ארנונה" נשבר לשתי שורות. כל משימה מתוזמנת היא שתי שורות, והטקסט
 * תמיד ברוחב מלא.
 */
export const controlsOnOwnLine = (task: { text: string; dueDate?: string }): boolean =>
  Boolean(task.dueDate) || task.text.length > LONG_TASK_CHARS;
